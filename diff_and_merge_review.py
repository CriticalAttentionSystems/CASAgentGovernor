#!/usr/bin/env python3
"""
diff_and_merge_review.py

Keeps a hand-graded review CSV in sync with a fresh grade_gemini_answers.py
run, without re-grading everything from scratch every time something
changes (e.g. after fixing the last-episode parsing bug, or after running
more Gemini episodes on a later day).

  diff   Compare a FRESH review CSV (freshly regenerated by
         grade_gemini_answers.py, ungraded) against your EXISTING graded
         CSV, and write out only the rows that are new -- i.e. not present
         in your existing graded file, keyed by
         (task_id, condition, repeat). Grade just this small diff instead
         of everything.

  merge  Combine your existing graded CSV with a diff CSV you've now
         finished grading, into one complete, up-to-date graded CSV.
         Refuses to guess (errors out instead) if there are duplicate
         keys, or if any row in the diff still has a blank
         'your_judgment'.

Usage:
    # After fixing a bug or running more episodes, regenerate the full
    # (ungraded) review from your logs under a NEW filename so you don't
    # overwrite your existing graded work:
    python3 grade_gemini_answers.py logs/gemini_run_*.log --csv review_fresh.csv

    # See only what's new since your last graded pass:
    python3 diff_and_merge_review.py diff \\
        --existing review_graded.csv \\
        --fresh review_fresh.csv \\
        --out review_diff.csv

    # ... grade review_diff.csv by hand (however few rows are in it) ...

    # Merge the newly-graded diff back into your complete graded set:
    python3 diff_and_merge_review.py merge \\
        --existing review_graded.csv \\
        --diff review_diff.csv \\
        --out review_graded_complete.csv

    # Then get final numbers:
    python3 aggregate_human_grades.py review_graded_complete.csv
"""

import argparse
import csv
import sys


def read_csv_rows(path):
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        rows = list(reader)
        fieldnames = reader.fieldnames
    if fieldnames is None:
        print(f"ERROR: {path} appears to be empty or has no header row.", file=sys.stderr)
        sys.exit(1)
    return rows, fieldnames


def row_key(row):
    return (row["task_id"], row["condition"], str(row["repeat"]))


def cmd_diff(args):
    existing_rows, _ = read_csv_rows(args.existing)
    fresh_rows, fresh_fields = read_csv_rows(args.fresh)

    existing_keys = {row_key(r) for r in existing_rows}
    new_rows = [r for r in fresh_rows if row_key(r) not in existing_keys]

    if not new_rows:
        print(f"No new rows found -- {args.fresh} and {args.existing} already "
              f"cover the same (task_id, condition, repeat) combinations. "
              f"Nothing new to grade.")
        return

    with open(args.out, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fresh_fields)
        writer.writeheader()
        writer.writerows(new_rows)

    print(f"Found {len(new_rows)} new row(s) not present in {args.existing}.")
    print(f"Wrote them to {args.out} -- grade just these (fill in "
          f"'your_judgment'), then run the 'merge' command.\n")
    for r in new_rows:
        print(f"  NEW: {r['task_id']} / {r['condition']} / repeat {r['repeat']}")


def cmd_merge(args):
    existing_rows, existing_fields = read_csv_rows(args.existing)
    diff_rows, diff_fields = read_csv_rows(args.diff)

    if existing_fields != diff_fields:
        print("WARNING: column headers differ between the two files:", file=sys.stderr)
        print(f"  existing: {existing_fields}", file=sys.stderr)
        print(f"  diff:     {diff_fields}", file=sys.stderr)
        print("Proceeding anyway, using the existing file's column order for output.\n", file=sys.stderr)

    ungraded_in_diff = [r for r in diff_rows if not r.get("your_judgment", "").strip()]
    if ungraded_in_diff:
        print(f"ERROR: {len(ungraded_in_diff)} row(s) in {args.diff} still have "
              f"a blank 'your_judgment'. Grade all of them before merging:",
              file=sys.stderr)
        for r in ungraded_in_diff:
            print(f"  UNGRADED: {r['task_id']} / {r['condition']} / repeat {r['repeat']}",
                  file=sys.stderr)
        sys.exit(1)

    existing_keys = {row_key(r) for r in existing_rows}
    conflicting = [r for r in diff_rows if row_key(r) in existing_keys]
    if conflicting:
        print(f"ERROR: {len(conflicting)} row(s) in {args.diff} already exist in "
              f"{args.existing} (same task_id/condition/repeat). Refusing to guess "
              f"which copy is right -- resolve this by hand first:", file=sys.stderr)
        for r in conflicting:
            print(f"  DUPLICATE KEY: {r['task_id']} / {r['condition']} / repeat {r['repeat']}",
                  file=sys.stderr)
        sys.exit(1)

    merged = existing_rows + diff_rows

    condition_order = {"ungoverned": 0, "governed": 1, "sham_regulation": 2}
    merged.sort(key=lambda r: (
        r["task_id"],
        condition_order.get(r["condition"], 99),
        int(r["repeat"]),
    ))

    with open(args.out, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=existing_fields)
        writer.writeheader()
        writer.writerows(merged)

    print(f"Merged {len(existing_rows)} existing + {len(diff_rows)} newly-graded "
          f"row(s) = {len(merged)} total. Wrote to {args.out}.")
    print(f"Run aggregate_human_grades.py against {args.out} for the complete, "
          f"up-to-date picture.")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    subparsers = parser.add_subparsers(dest="command", required=True)

    diff_parser = subparsers.add_parser("diff", help="Find rows in a fresh review CSV not yet in your graded CSV")
    diff_parser.add_argument("--existing", required=True, help="Your existing (partially or fully) graded CSV")
    diff_parser.add_argument("--fresh", required=True, help="A freshly regenerated (ungraded) review CSV")
    diff_parser.add_argument("--out", required=True, help="Where to write the new, ungraded rows")
    diff_parser.set_defaults(func=cmd_diff)

    merge_parser = subparsers.add_parser("merge", help="Merge a newly-graded diff back into your existing graded CSV")
    merge_parser.add_argument("--existing", required=True, help="Your existing graded CSV")
    merge_parser.add_argument("--diff", required=True, help="The diff CSV, now fully graded")
    merge_parser.add_argument("--out", required=True, help="Where to write the merged, complete graded CSV")
    merge_parser.set_defaults(func=cmd_merge)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
